def get_user_fio(login):  # Объявляем функцию получения ФИО по логину
    conn = psycopg2.connect(**DB_CONFIG)  # Устанавливаем соединение с БД, распаковывая словарь с конфигурацией
    try:  # Начинаем блок обработки исключений (отлова ошибок)
        with conn.cursor() as cur:  # Открываем курсор для выполнения SQL-запросов (with автоматически закроет его)
            # Выполняем безопасный SQL-запрос для поиска фамилии, имени и отчества пользователя по его логину
            cur.execute("SELECT users_name, familia, otchestvo FROM users WHERE login = %s;", (login,))
            row = cur.fetchone()  # Получаем первую (и единственную) строку с результатом запроса
            if row:  # Если запись в БД найдена
                # Формируем строку ФИО, заменяя возможные значения None пустой строкой, и убираем лишние пробелы по краям
                return f"{row[0] or ''} {row[1] or ''} {row[2] or ''}".strip()
    except Exception as e:  # Если при работе с БД произошла ошибка
        messagebox.showerror("Ошибка БД", str(e))  # Показываем всплывающее окно с текстом этой ошибки
    finally:  # Этот блок выполнится в любом случае (была ошибка или нет)
        conn.close()  # Обязательно закрываем соединение с базой данных
    return None  # Возвращаем None, если пользователь не найден или произошла ошибка


def show_main_screen(user_fio):  # Объявляем функцию для отрисовки главного экрана (после успешного входа)
    for w in root.winfo_children():  # Циклом перебираем все активные виджеты (элементы интерфейса) на главном окне
        w.destroy()  # Удаляем каждый виджет, чтобы полностью очистить экран перед отрисовкой нового содержимого
    root.title("Главная страница")  # Меняем заголовок главного окна
    root.geometry("600x400")  # Устанавливаем новый размер окна (ширина 600px, высота 400px)
    # Создаем приветственный текст (Label), форматируем его и размещаем (pack) с внутренним отступом по вертикали (pady)
    tk.Label(root, text=f"Добро пожаловать,\n{user_fio}!", font=("Arial", 18, "bold"), pady=30).pack()
    # Создаем подзаголовок серого цвета (fg="#555") и центрируем его на свободном пространстве (expand=True)
    tk.Label(root, text="Это ваша главная страница.", font=("Arial", 14), fg="#555").pack(expand=True)
    # Создаем красную кнопку "Выйти", которая при нажатии вызывает функцию возврата на экран логина
    tk.Button(root, text="Выйти", command=show_login_screen, bg="#f44336", fg="white", font=("Arial", 11), width=15).pack(side="bottom", pady=20)


def show_login_screen():  # Объявляем функцию для отрисовки экрана ввода логина
    for w in root.winfo_children():  # Снова перебираем все текущие виджеты на окне
        w.destroy()  # Удаляем их, полностью очищая окно
    root.title("Вход в систему")  # Устанавливаем заголовок для окна авторизации
    root.geometry("350x200")  # Задаем компактный размер окна (350x200px)
    root.resizable(False, False)  # Запрещаем пользователю менять размеры окна вручную (как по ширине, так и по высоте)
    # Создаем и размещаем текстовую метку с подсказкой "Введите логин:"
    tk.Label(root, text="Введите логин:", font=("Arial", 12)).pack(pady=20)
    # Создаем текстовое поле ввода (Entry) для ввода логина
    entry_login = tk.Entry(root, width=25, font=("Arial", 12))
    entry_login.pack()  # Размещаем поле ввода в окне
    entry_login.focus()  # Автоматически устанавливаем курсор в это поле ввода при открытии окна


    def handle_login():  # Вложенная функция для обработки процесса авторизации
        login = entry_login.get().strip()  # Считываем текст из поля ввода и удаляем случайные пробелы по краям
        if not login:  # Если поле оказалось пустым
            messagebox.showwarning("Ошибка", "Введите логин!")  # Показываем предупреждение о необходимости ввода
            return  # Прерываем выполнение функции
        fio = get_user_fio(login)  # Вызываем функцию поиска пользователя в БД по введенному логину
        if fio:  # Если ФИО успешно найдено (пользователь существует)
            show_main_screen(fio)  # Переключаем интерфейс на главный экран и передаем туда ФИО
        else:  # Если функция поиска вернула None
            messagebox.showerror("Ошибка", "Пользователь не найден!")  # Показываем окно с ошибкой авторизации
    # Привязываем событие нажатия клавиши Enter (<Return>) в поле ввода к вызову функции handle_login
    entry_login.bind('<Return>', lambda e: handle_login())
    # Создаем кнопку "Войти", которая при клике мышкой запускает функцию проверки handle_login
    tk.Button(root, text="Войти", command=handle_login, width=15).pack(pady=20)


if __name__ == "__main__":  # Проверяем, запущен ли скрипт напрямую (а не импортирован как модуль)
    root = tk.Tk()  # Создаем главное (корневое) окно приложения Tkinter
    show_login_screen()  # Инициализируем интерфейс, вызывая функцию отрисовки стартового экрана авторизации
    root.mainloop()  # Запускаем бесконечный главный цикл обработки событий Tkinter (чтобы окно не закрывалось)